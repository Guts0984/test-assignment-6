#!/usr/bin/env node
/**
 * Runs after `next build`. Lists every script and stylesheet of the build in public/precache.js, which
 * the offline service worker imports: it downloads them all when it is installed. Without this, a chunk
 * that is loaded lazily (the edit panel, the scope dialog, the repeat editor, settings) was never fetched
 * while online and could not be opened offline.
 *
 * The file's content changes with every build, and the browser re-checks imported scripts, so a new
 * deploy installs a new worker that precaches the new files.
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const root = '.next/static';
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.(js|css)$/.test(name))
      files.push('/_next/static/' + relative(root, path).split(sep).join('/'));
  }
})(root);
files.sort();

writeFileSync(
  'public/precache.js',
  `/* Generated by scripts/write-sw-manifest.mjs after the build. Do not edit. */\nself.PRECACHE = ${JSON.stringify(files, null, 1)};\n`,
);
console.log(`precache.js: ${files.length} files`);
